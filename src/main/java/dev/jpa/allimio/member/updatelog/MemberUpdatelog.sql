DROP TABLE MEMBER_UPDATELOG;

CREATE TABLE MEMBER_UPDATELOG (
	NO							NUMBER(10)			NOT NULL,     -- 회원 업데이트 로그 번호
	MNO							NUMBER(10)			NOT NULL,			-- 회원 번호
	CHANGED_COLUMN	VARCHAR2(20)		NOT NULL,  	 	-- 변경한 항목
	OLD_VALUE				VARCHAR2(100)		NULL,					-- 변경 전 값
	NEW_VALUE				VARCHAR2(100)		NOT NULL,			-- 변경 후 값
	CHANGE_DATE			VARCHAR2(19)		NOT NULL,			-- 변경 일시
	CHANGED_BY			NUMBER(1)				NOT NULL,			-- 변경자 유형(0: 관리자, 1: 회원)
	UPDT_MNNO  			NUMBER(10)     	NULL,					-- 변경한 관리자 번호(관리자가 변경한 경우)


	PRIMARY KEY (NO),
	FOREIGN KEY (MNO) REFERENCES MEMBER(NO),
	FOREIGN KEY (UPDT_MNNO) REFERENCES MANAGER(NO)
);

CREATE SEQUENCE MEMBER_UPDATELOG_SEQ START WITH 1 INCREMENT BY 1;

