CREATE TABLE CHAT_STATS_AI (
  NO           NUMBER(10)      NOT NULL,
  DAYS         NUMBER(5)       NOT NULL,
  FROM_DATE    VARCHAR2(10)    NOT NULL,
  TO_DATE      VARCHAR2(10)    NOT NULL,
  ANSWERED     NUMBER(10)      DEFAULT 0 NOT NULL,
  SCORE        NUMBER(3,1)     NOT NULL,
  SUMMARY      CLOB            NOT NULL,
  REASON       VARCHAR2(2000),
  WEAK_POINTS  CLOB,
  ANO          NUMBER(10),
  RDATE        VARCHAR2(30)    NOT NULL,
  CONSTRAINT PK_CHAT_STATS_AI PRIMARY KEY (NO)
);

CREATE SEQUENCE CHAT_STATS_AI_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE INDEX IDX_CHAT_STATS_AI_DAYS ON CHAT_STATS_AI (DAYS, NO);

COMMENT ON TABLE  CHAT_STATS_AI             IS '챗봇 상담 만족도 AI 분석 결과';
COMMENT ON COLUMN CHAT_STATS_AI.DAYS        IS '분석 기간(일) - 7/30/90';
COMMENT ON COLUMN CHAT_STATS_AI.FROM_DATE   IS '분석 시작일 yyyy-MM-dd';
COMMENT ON COLUMN CHAT_STATS_AI.TO_DATE     IS '분석 종료일 yyyy-MM-dd';
COMMENT ON COLUMN CHAT_STATS_AI.ANSWERED    IS '분석에 쓴 만족도 응답 수';
COMMENT ON COLUMN CHAT_STATS_AI.SCORE       IS '감정 점수 0~10';
COMMENT ON COLUMN CHAT_STATS_AI.SUMMARY     IS 'AI 요약';
COMMENT ON COLUMN CHAT_STATS_AI.REASON      IS '점수 근거';
COMMENT ON COLUMN CHAT_STATS_AI.WEAK_POINTS IS '개선할 점 (JSON 배열 문자열)';
COMMENT ON COLUMN CHAT_STATS_AI.ANO         IS '분석을 실행한 관리자 번호';
COMMENT ON COLUMN CHAT_STATS_AI.RDATE       IS '분석 일시 yyyy-MM-dd HH:mm:ss';